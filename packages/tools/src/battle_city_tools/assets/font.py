FALLBACK: Final[str] = "?"


def text_width(text: str, *, scale: int = 1, spacing: int = GLYPH_SPACING) -> int:
    """How wide ``text`` will be, in pixels, at ``scale``."""
    if not text:
        return 0
    return len(text) * (GLYPH_WIDTH * scale + spacing) - spacing


def draw_text(
    canvas: Canvas,
    text: str,
    x: int,
    y: int,
    color: Rgba,
    *,
    scale: int = 1,
    spacing: int = GLYPH_SPACING,
) -> int:
    """Draw ``text`` with its top left at ``(x, y)``. Returns the x after the last glyph."""
    cursor = x
    for character in text.upper():
        glyph = _GLYPHS.get(character, _GLYPHS[FALLBACK])
        for row, bits in enumerate(glyph):
            for column, bit in enumerate(bits):
                if bit != "#":
                    continue
                canvas.fill_rect(cursor + column * scale, y + row * scale, scale, scale, color)
        cursor += GLYPH_WIDTH * scale + spacing
    return cursor
